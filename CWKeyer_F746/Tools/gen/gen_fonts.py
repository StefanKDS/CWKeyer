#!/usr/bin/env python3
"""Generates anti-aliased 4 bpp bitmap fonts (Gui/Src/fonts.c, Gui/Inc/fonts.h)
from DejaVu TrueType fonts (Bitstream Vera / DejaVu license, free to embed).

Usage: python3 gen_fonts.py  (needs Pillow and DejaVu fonts)
"""
import os
from PIL import Image, ImageDraw, ImageFont

FONTDIR = os.environ.get("FONTDIR", "/usr/share/fonts/truetype/dejavu")
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")

BASIC = [chr(c) for c in range(0x20, 0x7F)] + list("ÄÖÜäöüß–·°…↔")
HUGE = list(" ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789?.,/=+-!@:()&$'\";_")

FONTS = [
    # name,        file,                    px,  charset
    ("font_small", "DejaVuSans.ttf",        13, BASIC),
    ("font_normal","DejaVuSans.ttf",        16, BASIC),
    ("font_bold",  "DejaVuSans-Bold.ttf",   16, BASIC),
    ("font_large", "DejaVuSans-Bold.ttf",   26, BASIC),
    ("font_mono",  "DejaVuSansMono.ttf",    20, BASIC),
    ("font_huge",  "DejaVuSans-Bold.ttf",   110, HUGE),
]


def render(path, px, chars):
    f = ImageFont.truetype(path, px)
    ascent, descent = f.getmetrics()
    glyphs, bitmap = [], bytearray()
    for ch in sorted(set(chars), key=ord):
        adv = int(round(f.getlength(ch)))
        img = Image.new("L", (px * 3, px * 3), 0)
        d = ImageDraw.Draw(img)
        ox, oy = px, px + ascent              # baseline position in image
        d.text((ox, oy), ch, font=f, fill=255, anchor="ls")
        bb = img.getbbox()
        if bb is None:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(bitmap)))
            continue
        x0, y0, x1, y1 = bb
        w, h = x1 - x0, y1 - y0
        off = len(bitmap)
        for y in range(y0, y1):
            row = []
            for x in range(x0, x1):
                row.append(img.getpixel((x, y)) >> 4)
            if len(row) % 2:
                row.append(0)
            for i in range(0, len(row), 2):
                bitmap.append((row[i] << 4) | row[i + 1])
        glyphs.append((ord(ch), w, h, x0 - ox, y0 - oy, adv, off))
    return ascent, descent, glyphs, bitmap


def main():
    c = ['/* Generated by Tools/gen/gen_fonts.py - do not edit.',
         ' * Glyphs rendered from DejaVu fonts (Bitstream Vera license). */',
         '#include "fonts.h"', '']
    h = ['/* Generated by Tools/gen/gen_fonts.py - do not edit. */',
         '#ifndef FONTS_H', '#define FONTS_H', '', '#include <stdint.h>', '',
         'typedef struct', '{',
         '    uint16_t cp;      /**< unicode code point                */',
         '    uint8_t  w, h;    /**< bitmap size                       */',
         '    int8_t   xo, yo;  /**< offset from pen / baseline        */',
         '    uint8_t  adv;     /**< advance width                     */',
         '    uint32_t off;     /**< offset into bitmap (4 bpp, rows)  */',
         '} glyph_t;', '',
         'typedef struct', '{',
         '    const glyph_t *glyphs;', '    const uint8_t *bitmap;',
         '    uint16_t       count;', '    uint8_t        ascent;',
         '    uint8_t        height;', '} font_t;', '']
    total = 0
    for name, file, px, chars in FONTS:
        asc, desc, glyphs, bm = render(os.path.join(FONTDIR, file), px, chars)
        total += len(bm) + len(glyphs) * 12
        c.append(f'static const uint8_t {name}_bm[{len(bm)}] = {{')
        for i in range(0, len(bm), 24):
            c.append('    ' + ','.join(f'0x{b:02X}' for b in bm[i:i + 24]) + ',')
        c.append('};')
        c.append(f'static const glyph_t {name}_gl[{len(glyphs)}] = {{')
        for g in glyphs:
            c.append('    {0x%04X,%d,%d,%d,%d,%d,%d},' % g)
        c.append('};')
        c.append(f'const font_t {name} = {{ {name}_gl, {name}_bm, {len(glyphs)}, {asc}, {asc + desc} }};')
        c.append('')
        h.append(f'extern const font_t {name};   /* {file} {px}px */')
    h += ['', '#endif', '']
    open(os.path.join(ROOT, 'Gui/Src/fonts.c'), 'w').write('\n'.join(c))
    open(os.path.join(ROOT, 'Gui/Inc/fonts.h'), 'w').write('\n'.join(h))
    print(f'fonts: {total/1024:.1f} KiB')


if __name__ == '__main__':
    main()
